@pytest.mark.parametrize("name", sorted(TABLE))
def test_every_attribute_still_resolves_to_the_same_code(name):
    now = _fingerprint(CLASSES[name])
    expected = TABLE[name]
    lost = set(expected) - set(now)
    assert not lost, f"{name} lost {sorted(lost)}"
    gained = set(now) - set(expected) - ADDED
    assert not gained, f"{name} gained {sorted(gained)}"
    allowed = {attr for attr, names in CHANGED_BY_ATTRIBUTE.items() if name in names}
    changed = {attr for attr in expected if now[attr] != expected[attr]}
    assert changed == allowed, (
        f"{name}: changed but not listed {sorted(changed - allowed)}; "
        f"listed but unchanged {sorted(allowed - changed)}"
    )


