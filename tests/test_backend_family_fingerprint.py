def _fingerprint(cls) -> dict[str, str]:
    out = {}
    for name in sorted(dir(cls)):
        if name.startswith("__") or name == "_abc_impl":
            continue
        raw = inspect.getattr_static(cls, name)
        if isinstance(raw, (staticmethod, classmethod)):
            raw = raw.__func__
        if isinstance(raw, property):
            parts = [inspect.getsource(f) for f in (raw.fget, raw.fset, raw.fdel) if f]
            text = "property:" + "".join(parts)
        elif inspect.isfunction(raw):
            text = textwrap.dedent(inspect.getsource(raw))
        elif isinstance(raw, (int, float, str, bool, tuple, frozenset, type(None))):
            text = "value:" + repr(raw)
        elif isinstance(raw, (dict, list)):
            text = "value:" + repr(sorted(raw.items(), key=repr) if isinstance(raw, dict) else raw)
        else:
            text = "object:" + type(raw).__name__
        out[name] = hashlib.sha1(text.encode()).hexdigest()[:10]
    return out


def _family() -> dict[str, type]:
    seen, todo = [], [WineGameBackend]
    while todo:
        cls = todo.pop()
        if cls not in seen:
            seen.append(cls)
            todo.extend(cls.__subclasses__())
    names = [cls.__name__ for cls in seen]
    out = {}
    for cls in seen:
        if cls is WineGameBackend:
            continue
        unique = names.count(cls.__name__) == 1
        key = cls.__name__ if unique else f"{cls.__module__.rsplit('.', 1)[-1]}.{cls.__name__}"
        out[key] = cls
    return out


