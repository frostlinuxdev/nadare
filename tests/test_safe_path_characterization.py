FUNCS = {
    "direct": directdl.safe_relative_path,
    "sophon": sophon._safe_relative_path,
    "yostar": yostar.safe_relative_path,
}


@pytest.mark.parametrize(("name", "value"), list(TABLE), ids=[f"{n}-{v!r}" for n, v in TABLE])
def test_validator_behaves_as_before(name, value):
    expected = TABLE[(name, value)]
    func = FUNCS[name]
    if expected[0] == "ok":
        assert func(value) == expected[1]
        return
    with pytest.raises(Exception) as caught:  # noqa: PT011 - the type is checked by name below
        func(value)
    assert type(caught.value).__name__ == expected[1]
    assert str(caught.value) == expected[2]
